export const WEAPON_MAP = Object.fromEntries(WEAPONS.map((w) => [w.id, w]));

export function getWeaponUpgradeCost(weaponId, currentTier) {
  const w = WEAPON_MAP[weaponId];
  const base = Math.max(120, Math.round((w.unlockCoins || 160) * 0.45));
  return {
    coins: Math.round(base * Math.pow(1.55, currentTier - 1)),
    gems: currentTier >= 4 ? (currentTier - 2) * 3 : 0,
  };
}

export function getWeaponTierMultiplier(tier) {
  return 1 + (tier - 1) * 0.16;
}
